-- 02: least-privilege grants + schema layout. Idempotent. Run as ACCOUNTADMIN.
USE ROLE SECURITYADMIN;

-- Warehouses
GRANT USAGE, OPERATE ON WAREHOUSE LOADING_WH   TO ROLE LOADER;
GRANT USAGE, OPERATE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT USAGE          ON WAREHOUSE BI_WH        TO ROLE REPORTER;

-- RAW: LOADER creates and owns what Airbyte writes (AIRBYTE = typed tables, AIRBYTE_INTERNAL = raw JSON).
GRANT USAGE, CREATE SCHEMA ON DATABASE SHOPSPHERE_RAW TO ROLE LOADER;
-- TRANSFORMER reads everything LOADER creates, now and in the future (Airbyte may recreate tables).
GRANT USAGE ON DATABASE SHOPSPHERE_RAW                   TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE SHOPSPHERE_RAW    TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE SHOPSPHERE_RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE SHOPSPHERE_RAW    TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE SHOPSPHERE_RAW TO ROLE TRANSFORMER;

-- ANALYTICS family: dbt (TRANSFORMER) builds everything.
GRANT USAGE, CREATE SCHEMA ON DATABASE SHOPSPHERE_ANALYTICS     TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE SHOPSPHERE_ANALYTICS_DEV TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE SHOPSPHERE_ANALYTICS TO ROLE REPORTER;

USE ROLE LOADER;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_RAW.AIRBYTE;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_RAW.AIRBYTE_INTERNAL;

USE ROLE TRANSFORMER;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_ANALYTICS.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_ANALYTICS.MARTS;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_ANALYTICS.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS SHOPSPHERE_ANALYTICS.GOVERNANCE;

USE ROLE SECURITYADMIN;
-- REPORTER (BI): MARTS only. Future grants survive dbt's CREATE OR REPLACE on full refresh.
GRANT USAGE ON SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES          IN SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL VIEWS           IN SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL DYNAMIC TABLES  IN SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA SHOPSPHERE_ANALYTICS.MARTS TO ROLE REPORTER;

-- ANALYST (humans): inherits REPORTER, plus the modelling layers for investigation.
GRANT USAGE ON SCHEMA SHOPSPHERE_ANALYTICS.STAGING      TO ROLE ANALYST;
GRANT USAGE ON SCHEMA SHOPSPHERE_ANALYTICS.INTERMEDIATE TO ROLE ANALYST;
GRANT SELECT ON ALL VIEWS    IN SCHEMA SHOPSPHERE_ANALYTICS.STAGING      TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SHOPSPHERE_ANALYTICS.STAGING      TO ROLE ANALYST;
GRANT SELECT ON ALL VIEWS    IN SCHEMA SHOPSPHERE_ANALYTICS.INTERMEDIATE TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SHOPSPHERE_ANALYTICS.INTERMEDIATE TO ROLE ANALYST;
