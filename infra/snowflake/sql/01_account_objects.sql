-- 01: roles, databases, warehouses, resource monitor. Idempotent. Run as ACCOUNTADMIN.
-- Warehouses are split by workload so credit usage is attributable.

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOADER      COMMENT = 'Airbyte: writes to SHOPSPHERE_RAW';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'dbt: reads RAW, owns ANALYTICS objects';
CREATE ROLE IF NOT EXISTS REPORTER    COMMENT = 'BI tools: read-only on MARTS';
CREATE ROLE IF NOT EXISTS ANALYST     COMMENT = 'Humans: REPORTER + read on STAGING/INTERMEDIATE';
CREATE ROLE IF NOT EXISTS PII_READER  COMMENT = 'Sees unmasked PII columns; grant sparingly';
GRANT ROLE REPORTER TO ROLE ANALYST;
-- Everything rolls up to SYSADMIN so object ownership stays manageable.
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE ANALYST     TO ROLE SYSADMIN;
GRANT ROLE PII_READER  TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS SHOPSPHERE_RAW           COMMENT = 'Airbyte landing zone (CDC change log)';
CREATE DATABASE IF NOT EXISTS SHOPSPHERE_ANALYTICS     COMMENT = 'Production dbt output';
CREATE DATABASE IF NOT EXISTS SHOPSPHERE_ANALYTICS_DEV COMMENT = 'Developer sandboxes (schema per developer)';

CREATE WAREHOUSE IF NOT EXISTS LOADING_WH   WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'Airbyte loads';
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH WITH WAREHOUSE_SIZE = 'SMALL'  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'dbt builds and dynamic tables';
CREATE WAREHOUSE IF NOT EXISTS BI_WH        WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'Dashboards and ad-hoc analysis';

-- Credit guardrail: notify at 75%, suspend at 90%, hard stop at 100%.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS SHOPSPHERE_RM
    WITH CREDIT_QUOTA = ${SNOWFLAKE_MONTHLY_CREDIT_QUOTA}
         FREQUENCY = MONTHLY
         START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 75 PERCENT DO NOTIFY
             ON 90 PERCENT DO SUSPEND
             ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE LOADING_WH   SET RESOURCE_MONITOR = SHOPSPHERE_RM;
ALTER WAREHOUSE TRANSFORM_WH SET RESOURCE_MONITOR = SHOPSPHERE_RM;
ALTER WAREHOUSE BI_WH        SET RESOURCE_MONITOR = SHOPSPHERE_RM;
